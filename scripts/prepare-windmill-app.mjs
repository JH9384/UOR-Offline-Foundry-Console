import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';
import esbuild from 'esbuild';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = path.resolve(__dirname, '..');
const SHARED_SRC_DIR = path.join(ROOT_DIR, 'src', 'shared');
const RAW_APP_DIR = path.join(ROOT_DIR, 'uor_foundry.raw_app');
const STAGED_SHARED_DIR = path.join(RAW_APP_DIR, 'shared');
const LEGACY_STAGED_SRC_DIR = path.join(RAW_APP_DIR, 'src');
const LEGACY_STAGED_CSS_FILE = path.join(RAW_APP_DIR, 'index.css');
const GENERATED_REGISTRY_FILE = path.join(RAW_APP_DIR, 'backend', 'generated_command_registry.ts');
const GENERATED_FLOW_FILE = path.join(RAW_APP_DIR, 'flows', 'prism_hologram_delivery.flow.json');

const verifyOnly = process.argv.includes('--verify');

async function loadCanonicalCommandRegistry() {
  const entryFile = path.join(SHARED_SRC_DIR, 'adapters', 'windmillCommandRegistry.ts');
  const tmpFile = path.join(
    os.tmpdir(),
    `uor-canonical-registry-${process.pid}-${Date.now()}.mjs`
  );
  try {
    await esbuild.build({
      entryPoints: [entryFile],
      bundle: true,
      format: 'esm',
      platform: 'node',
      target: 'node20',
      outfile: tmpFile,
      logLevel: 'silent',
    });
    return await import(`${pathToFileURL(tmpFile).href}?t=${Date.now()}`);
  } finally {
    fs.rmSync(tmpFile, { force: true });
  }
}

function renderGeneratedBackendRegistryTs(mod) {
  const mapObj = {};
  for (const entry of mod.FIXED_WINDMILL_COMMAND_REGISTRY) {
    mapObj[entry.commandId] = {
      commandId: entry.commandId,
      executable: entry.executable,
      fixedArgs: entry.fixedArgs,
      stageContractName: entry.stageContractName,
      windmillRunnable: entry.windmillRunnable,
      windmillFlowPath: entry.windmillFlowPath,
      allowedWorkspaces: entry.allowedWorkspaces,
      requiresOperatorApproval: entry.requiresOperatorApproval,
    };
  }

  return `/**
 * AUTO-GENERATED BY scripts/prepare-windmill-app.mjs FROM
 * src/shared/adapters/windmillCommandRegistry.ts — DO NOT HAND-EDIT.
 */
export interface FixedCommandSpec {
  commandId: string;
  executable: 'prismpm' | 'lexlean' | 'hologram' | 'uorust' | 'node';
  fixedArgs: readonly string[];
  stageContractName: string;
  windmillRunnable: string;
  windmillFlowPath: string;
  allowedWorkspaces: readonly ['uor-offline-foundry'];
  requiresOperatorApproval: boolean;
}

export const ALLOWED_WINDMILL_WORKSPACE = ${JSON.stringify(mod.ALLOWED_WINDMILL_WORKSPACE)} as const;

export const FIXED_STAGE_COMMANDS: Record<string, FixedCommandSpec> = ${JSON.stringify(
    mapObj,
    null,
    2
  )};

export const ALLOWED_COMMAND_IDS = new Set<string>(Object.keys(FIXED_STAGE_COMMANDS));

const SHELL_METACHAR_REGEX = /[;&|\`$<>()\\n\\r\\\\*?~]/;
const SAFE_RELATIVE_PATH_REGEX = /^[a-zA-Z0-9._/-]+$/;
const SAFE_REVISION_REGEX = /^[a-zA-Z0-9._/@:-]{4,128}$/;

export function buildValidatedArgv(spec: FixedCommandSpec, relPath: string): string[] {
  const holoRef = \`\${relPath}/dist/app.holo\`;
  switch (spec.executable) {
    case 'prismpm':
      if (spec.commandId === 'prismpm_export_browser') {
        return ['prismpm', '--project', relPath, 'export-browser', holoRef, '--output', \`\${relPath}/dist/browser\`];
      }
      return ['prismpm', '--project', relPath, ...spec.fixedArgs];
    case 'lexlean':
      return ['lexlean', '--project', \`\${relPath}/lexlean.toml\`, ...spec.fixedArgs];
    case 'hologram':
      return ['hologram', ...spec.fixedArgs, holoRef];
    case 'uorust':
      return ['uorust', 'project', relPath, '--out', \`\${relPath}/.prism/projection\`];
    case 'node':
      return ['node', ...spec.fixedArgs, '--project', relPath];
  }
}

export function validateRegistryDispatch(params: {
  workspace?: string;
  commandId?: string;
  rawCommandString?: string;
  projectRelativePath: string;
  sourceRevision: string;
}): {
  allowed: boolean;
  status: 'ALLOWED' | 'REJECTED_INVALID_COMMAND';
  spec?: FixedCommandSpec;
  validatedArgv?: string[];
  reason: string;
} {
  const workspace = (params.workspace ?? ALLOWED_WINDMILL_WORKSPACE).trim();
  if (workspace !== ALLOWED_WINDMILL_WORKSPACE) {
    return {
      allowed: false,
      status: 'REJECTED_INVALID_COMMAND',
      reason: \`Unauthorized workspace "\${workspace}". Only "\${ALLOWED_WINDMILL_WORKSPACE}" is allowed.\`,
    };
  }
  if (params.rawCommandString !== undefined) {
    return {
      allowed: false,
      status: 'REJECTED_INVALID_COMMAND',
      reason: 'Refused arbitrary raw shell/chat command string. Only fixed commandId identifiers may be scheduled.',
    };
  }
  const spec = params.commandId ? FIXED_STAGE_COMMANDS[params.commandId] : undefined;
  if (!spec) {
    return {
      allowed: false,
      status: 'REJECTED_INVALID_COMMAND',
      reason: \`Refused unknown commandId "\${params.commandId ?? 'MISSING'}": not in fixed Windmill command registry.\`,
    };
  }
  const relPath = params.projectRelativePath.trim();
  if (
    !relPath ||
    relPath.startsWith('/') ||
    relPath.includes('..') ||
    SHELL_METACHAR_REGEX.test(relPath) ||
    !SAFE_RELATIVE_PATH_REGEX.test(relPath)
  ) {
    return {
      allowed: false,
      status: 'REJECTED_INVALID_COMMAND',
      reason: \`Refused unsafe or non-confined projectRelativePath "\${params.projectRelativePath}".\`,
    };
  }
  const rev = params.sourceRevision.trim();
  if (!SAFE_REVISION_REGEX.test(rev) || SHELL_METACHAR_REGEX.test(rev)) {
    return {
      allowed: false,
      status: 'REJECTED_INVALID_COMMAND',
      reason: \`Refused malformed sourceRevision "\${params.sourceRevision}".\`,
    };
  }
  return {
    allowed: true,
    status: 'ALLOWED',
    spec,
    validatedArgv: buildValidatedArgv(spec, relPath),
    reason: \`Validated fixed commandId "\${spec.commandId}".\`,
  };
}
`;
}

function renderGeneratedFlowJson(mod) {
  return `${JSON.stringify(mod.buildCanonicalPrismFlowManifest(), null, 2)}\n`;
}

function renderInlineRegistryBlock(mod) {
  const commandIds = mod.FIXED_WINDMILL_COMMAND_REGISTRY.map((entry) => entry.commandId);
  return `// [AUTO-SYNCED-REGISTRY-START]
export const ALLOWED_WINDMILL_WORKSPACE = ${JSON.stringify(mod.ALLOWED_WINDMILL_WORKSPACE)} as const;

export const CANONICAL_COMMAND_IDS = ${JSON.stringify(commandIds, null, 2)} as const;
// [AUTO-SYNCED-REGISTRY-END]`;
}

function syncRuntimeHealthInlineRegistry(mod) {
  const inlineBlock = renderInlineRegistryBlock(mod);
  const blockRegex = /\/\/ \[AUTO-SYNCED-REGISTRY-START\][\s\S]*?\/\/ \[AUTO-SYNCED-REGISTRY-END\]/;
  for (const filename of ['runtime_health.ts', 'job_status.ts']) {
    const filePath = path.join(RAW_APP_DIR, 'backend', filename);
    const existing = fs.readFileSync(filePath, 'utf8');
    if (!blockRegex.test(existing)) {
      throw new Error(
        `uor_foundry.raw_app/backend/${filename} is missing // [AUTO-SYNCED-REGISTRY-START] ... // [AUTO-SYNCED-REGISTRY-END] markers.`
      );
    }
    const updated = existing.replace(blockRegex, inlineBlock);
    fs.writeFileSync(filePath, updated, 'utf8');
  }
}

const BACKEND_RUNNABLE_FILES = [
  'runtime_health.ts',
  'intake_validate.ts',
  'job_status.ts',
  'local_ai_advisory.ts',
  'workflow_dispatch.ts',
  'prism_stage_dispatch.ts',
];

async function bundleStandaloneWindmillRunnables() {
  const outDir = path.join(RAW_APP_DIR, 'dist', 'windmill');
  fs.rmSync(outDir, { recursive: true, force: true });
  fs.mkdirSync(outDir, { recursive: true });

  for (const filename of BACKEND_RUNNABLE_FILES) {
    const entryPoint = path.join(RAW_APP_DIR, 'backend', filename);
    const outfile = path.join(outDir, filename);
    await esbuild.build({
      entryPoints: [entryPoint],
      bundle: true,
      format: 'esm',
      platform: 'node',
      target: 'es2022',
      outfile,
      banner: {
        js: `// @ts-nocheck\n// AUTO-BUNDLED STANDALONE WINDMILL RUNNABLE (${filename}) — ZERO RELATIVE IMPORTS`,
      },
      logLevel: 'silent',
    });
  }
}

function copyDirFiltered(src, dest) {
  fs.mkdirSync(dest, { recursive: true });
  const entries = fs.readdirSync(src, { withFileTypes: true });
  for (const entry of entries) {
    if (entry.name === 'tests' || /\.test\.[tj]sx?$/.test(entry.name) || /\.spec\.[tj]sx?$/.test(entry.name)) {
      continue;
    }
    const srcPath = path.join(src, entry.name);
    const destPath = path.join(dest, entry.name);
    if (entry.isDirectory()) {
      copyDirFiltered(srcPath, destPath);
    } else if (entry.isFile()) {
      fs.copyFileSync(srcPath, destPath);
    }
  }
}

function collectCodeFiles(dir, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === 'node_modules' || entry.name === 'dist') continue;
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      collectCodeFiles(fullPath, out);
    } else if (/\.(ts|tsx|js|jsx|mjs|css)$/.test(entry.name)) {
      out.push(fullPath);
    }
  }
  return out;
}

async function prepare() {
  if (!fs.existsSync(SHARED_SRC_DIR)) {
    throw new Error(`Missing shared source library directory: ${SHARED_SRC_DIR}`);
  }
  const registryMod = await loadCanonicalCommandRegistry();

  // Remove legacy staged Vite-shaped copies (`src/` & `index.css`) if present
  fs.rmSync(LEGACY_STAGED_SRC_DIR, { recursive: true, force: true });
  fs.rmSync(LEGACY_STAGED_CSS_FILE, { force: true });

  fs.rmSync(STAGED_SHARED_DIR, { recursive: true, force: true });
  copyDirFiltered(SHARED_SRC_DIR, STAGED_SHARED_DIR);

  fs.mkdirSync(path.dirname(GENERATED_REGISTRY_FILE), { recursive: true });
  fs.writeFileSync(GENERATED_REGISTRY_FILE, renderGeneratedBackendRegistryTs(registryMod), 'utf8');

  syncRuntimeHealthInlineRegistry(registryMod);

  fs.mkdirSync(path.dirname(GENERATED_FLOW_FILE), { recursive: true });
  fs.writeFileSync(GENERATED_FLOW_FILE, renderGeneratedFlowJson(registryMod), 'utf8');

  await bundleStandaloneWindmillRunnables();

  const sharedCss = path.join(STAGED_SHARED_DIR, 'index.css');
  if (!fs.existsSync(sharedCss)) {
    throw new Error(`Missing shared CSS entrypoint after sync: ${sharedCss}`);
  }
  console.log(
    '[windmill:prepare] Synced src/shared/ -> uor_foundry.raw_app/shared/, generated backend/generated_command_registry.ts + flows/prism_hologram_delivery.flow.json, and bundled standalone runnables in uor_foundry.raw_app/dist/windmill/'
  );
  return registryMod;
}

async function validate(registryMod) {
  const requiredFiles = [
    'raw_app.yaml',
    'package.json',
    'tsconfig.json',
    'App.tsx',
    'index.tsx',
    'shared/App.tsx',
    'shared/index.ts',
    'shared/index.css',
    'wmill.contract.ts',
    'backend/runtime_health.ts',
    'backend/local_ai_advisory.ts',
    'backend/intake_validate.ts',
    'backend/generated_command_registry.ts',
    'backend/workflow_dispatch.ts',
    'backend/prism_stage_dispatch.ts',
    'backend/job_status.ts',
    'flows/prism_hologram_delivery.flow.json',
    ...BACKEND_RUNNABLE_FILES.map((f) => `dist/windmill/${f}`),
  ];

  for (const rel of requiredFiles) {
    const abs = path.join(RAW_APP_DIR, rel);
    if (!fs.existsSync(abs)) {
      throw new Error(`Missing required Windmill raw_app file: uor_foundry.raw_app/${rel}`);
    }
  }

  // Verify generated backend registry and flow manifest match canonical source 1-to-1
  const expectedRegistryTs = renderGeneratedBackendRegistryTs(registryMod);
  const actualRegistryTs = fs.readFileSync(GENERATED_REGISTRY_FILE, 'utf8');
  if (actualRegistryTs !== expectedRegistryTs) {
    throw new Error('Drift detected in uor_foundry.raw_app/backend/generated_command_registry.ts');
  }

  // Verify runtime_health.ts and job_status.ts have zero relative imports and match canonical registry 1-to-1
  const relativeImportRegex = /(?:from|import)\s*['"](\.[^'"]+)['"]|import\(\s*['"](\.[^'"]+)['"]\s*\)/;
  for (const selfContainedFile of ['runtime_health.ts', 'job_status.ts']) {
    const src = fs.readFileSync(path.join(RAW_APP_DIR, 'backend', selfContainedFile), 'utf8');
    if (!src.includes(renderInlineRegistryBlock(registryMod))) {
      throw new Error(`Drift detected in uor_foundry.raw_app/backend/${selfContainedFile} inline registry block`);
    }
    if (relativeImportRegex.test(src)) {
      throw new Error(`uor_foundry.raw_app/backend/${selfContainedFile} must not contain relative imports so it deploys cleanly in Windmill.`);
    }
  }

  // Verify all bundled standalone runnables in dist/windmill/ have zero relative imports
  for (const filename of BACKEND_RUNNABLE_FILES) {
    const bundledSrc = fs.readFileSync(path.join(RAW_APP_DIR, 'dist', 'windmill', filename), 'utf8');
    if (relativeImportRegex.test(bundledSrc)) {
      throw new Error(`Standalone bundled runnable uor_foundry.raw_app/dist/windmill/${filename} contains unresolved relative import.`);
    }
  }

  const flowJson = JSON.parse(fs.readFileSync(GENERATED_FLOW_FILE, 'utf8'));
  const expectedFlowJson = registryMod.buildCanonicalPrismFlowManifest();
  if (JSON.stringify(flowJson) !== JSON.stringify(expectedFlowJson)) {
    throw new Error('Drift detected in uor_foundry.raw_app/flows/prism_hologram_delivery.flow.json');
  }

  // Ensure every flow stage resolves 1-to-1 to exactly one registered canonical command
  for (const stage of flowJson.stages) {
    const matches = registryMod.FIXED_WINDMILL_COMMAND_REGISTRY.filter(
      (entry) => entry.commandId === stage.fixedCommandId
    );
    if (matches.length !== 1) {
      throw new Error(
        `Flow stage ${stage.stageContractName} has non-unique or missing fixedCommandId "${stage.fixedCommandId}".`
      );
    }
    if (matches[0].windmillRunnable !== stage.runnable) {
      throw new Error(
        `Flow stage ${stage.stageContractName} runnable "${stage.runnable}" disagrees with registry "${matches[0].windmillRunnable}".`
      );
    }
  }

  // Ensure handwritten wmill.ts is not checked in or fabricated
  const handwrittenWmill = path.join(RAW_APP_DIR, 'wmill.ts');
  if (fs.existsSync(handwrittenWmill)) {
    throw new Error('uor_foundry.raw_app/wmill.ts must only be generated by `wmill app dev`, not handwritten.');
  }

  // Validate raw_app.yaml locks out public/guest execution
  const yaml = fs.readFileSync(path.join(RAW_APP_DIR, 'raw_app.yaml'), 'utf8');
  if (!/^\s*public:\s*false\s*$/m.test(yaml) || !/^\s*guests:\s*false\s*$/m.test(yaml)) {
    throw new Error('uor_foundry.raw_app/raw_app.yaml must enforce `public: false` and `guests: false`.');
  }

  // Validate zero imports escape RAW_APP_DIR and zero embedded credentials
  const files = collectCodeFiles(RAW_APP_DIR);
  const importRegex = /(?:from|import)\s*['"](\.[^'"]+)['"]|import\(\s*['"](\.[^'"]+)['"]\s*\)/g;
  const secretRegex = /(?:Bearer\s+[A-Za-z0-9._-]{12,}|sk-[A-Za-z0-9]{16,}|WMILL_TOKEN\s*=\s*['"][^'"]+['"])/;

  for (const file of files) {
    const rel = path.relative(ROOT_DIR, file);
    const content = fs.readFileSync(file, 'utf8');
    let match;
    while ((match = importRegex.exec(content)) !== null) {
      const specifier = match[1] || match[2];
      const resolved = path.resolve(path.dirname(file), specifier);
      if (resolved !== RAW_APP_DIR && !resolved.startsWith(`${RAW_APP_DIR}${path.sep}`)) {
        throw new Error(`Import escapes uor_foundry.raw_app boundary ("${specifier}") in ${rel}`);
      }
    }
    if (secretRegex.test(content)) {
      throw new Error(`Prohibited hardcoded credential pattern detected in ${rel}`);
    }
  }

  // Validate package.json dependency closure
  const rawPkg = JSON.parse(fs.readFileSync(path.join(RAW_APP_DIR, 'package.json'), 'utf8'));
  const deps = { ...(rawPkg.dependencies || {}), ...(rawPkg.devDependencies || {}) };
  for (const requiredDep of ['react', 'react-dom', 'lucide-react', 'tailwindcss', '@tailwindcss/vite', 'typescript', 'vite', '@vitejs/plugin-react']) {
    if (!deps[requiredDep]) {
      throw new Error(`uor_foundry.raw_app/package.json is missing required dependency: ${requiredDep}`);
    }
  }

  // Run standalone TypeScript typecheck against staged Windmill raw_app
  const tscBin = path.join(ROOT_DIR, 'node_modules', '.bin', process.platform === 'win32' ? 'tsc.cmd' : 'tsc');
  execFileSync(tscBin, ['--noEmit', '-p', path.join(RAW_APP_DIR, 'tsconfig.json')], {
    cwd: ROOT_DIR,
    stdio: 'inherit',
  });

  console.log('[windmill:validate] PASS: zero parent imports, canonical registry & flow JSON synced 1-to-1, standalone tsc --noEmit passed.');
  console.log('[windmill:validate] Packaging status: PREPARED — LOCAL VALIDATION REQUIRED (`wmill app dev` in uor-offline-foundry).');
}

const mod = await prepare();
if (verifyOnly) {
  await validate(mod);
}
