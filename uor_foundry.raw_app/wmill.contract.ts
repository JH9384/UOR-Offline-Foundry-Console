/**
 * Type-safe Windmill `wmill.ts` adapter contract.
 *
 * IMPORTANT:
 * Do NOT handwrite or counterfeit `./wmill.ts`.
 * When developing or packaging locally inside `uor-offline-foundry`,
 * run `wmill app dev` to let the Windmill CLI generate `./wmill.ts`
 * directly from the runnables in `./backend/`.
 *
 * Documented methods referenced from:
 * - https://www.windmill.dev/docs/full_code_apps/frontend
 */

export interface WindmillJobSnapshot<T = unknown> {
  id: string;
  running: boolean;
  success?: boolean;
  result?: T;
  logs?: string;
}

export interface GeneratedWmillBindingsContract {
  backend: {
    runtime_health: (args: { workspace: string }) => Promise<unknown>;
    intake_validate: (args: {
      projectName: string;
      productFamily: string;
      componentId: string;
      workflowId: string;
      purpose: string;
      declaredInputs: string;
      environmentDeclaration: string;
      sourceRevision: string;
      acknowledgeBoundary: boolean;
    }) => Promise<unknown>;
  };
  backendAsync: {
    local_ai_advisory: (
      args: {
        projectId: string;
        prompt: string;
        referencedElementLabel?: string;
      },
      options?: { memoryId?: string }
    ) => Promise<string>;
    workflow_dispatch: (args: {
      projectId: string;
      flowPath: string;
      sourceRevision: string;
      idempotencyKey: string;
      operatorApproved: boolean;
    }) => Promise<string>;
    job_status: (args: { jobId: string }) => Promise<string>;
  };
  getJob: (jobId: string) => Promise<WindmillJobSnapshot>;
  waitJob: <T = unknown>(jobId: string) => Promise<T>;
  streamJob: (
    jobId: string,
    onChunk: (chunk: string) => void
  ) => Promise<void>;
}

/**
 * Fail-closed guard used when `./wmill.ts` has not yet been generated by `wmill app dev`.
 */
export function requireGeneratedWmillModule(): never {
  throw new Error(
    'Windmill native runtime unavailable: run `wmill app dev` against workspace `uor-offline-foundry` to generate `./wmill.ts`.'
  );
}
