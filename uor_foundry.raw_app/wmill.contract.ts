/**
 * Type-safe Windmill `wmill.ts` adapter contract.
 *
 * IMPORTANT:
 * Do NOT handwrite or counterfeit `./wmill.ts`.
 * When developing or packaging locally inside `uor-offline-foundry`,
 * run `wmill app dev` to let the Windmill CLI generate `./wmill.ts`
 * directly from the runnables in `./backend/`.
 *
 * Documented methods referenced from:
 * - https://www.windmill.dev/docs/full_code_apps/frontend
 */

export interface WindmillJobSnapshot<T = unknown> {
  id: string;
  running: boolean;
  success?: boolean;
  result?: T;
  logs?: string;
}

export interface GeneratedWmillBindingsContract {
  backend: {
    runtime_health: (args: { workspace: string }) => Promise<unknown>;
    intake_validate: (args: {
      projectName: string;
      productFamily: string;
      componentId: string;
      workflowId: string;
      purpose: string;
      declaredInputs: string;
      environmentDeclaration: string;
      sourceRevision: string;
      acknowledgeBoundary: boolean;
    }) => Promise<unknown>;
  };
  backendAsync: {
    local_ai_advisory: (
      args: {
        projectId: string;
        prompt: string;
        referencedElementLabel?: string;
      },
      options?: { memoryId?: string }
    ) => Promise<string>;
    workflow_dispatch: (args: {
      projectId: string;
      flowPath: string;
      sourceRevision: string;
      idempotencyKey: string;
      operatorApproved: boolean;
    }) => Promise<string>;
    prism_stage_dispatch: (args: {
      commandId: string;
      stageId?: string;
      projectId?: string;
      sourceRevision: string;
      projectRelativePath: string;
      idempotencyKey: string;
      operatorApproved: boolean;
    }) => Promise<string>;
    job_status: (args: { jobId: string }) => Promise<string>;
  };
  getJob: (jobId: string) => Promise<WindmillJobSnapshot>;
  waitJob: <T = unknown>(jobId: string) => Promise<T>;
  streamJob: (
    jobId: string,
    onChunk: (chunk: string) => void
  ) => Promise<void>;
}

export const REQUIRED_WINDMILL_SYNC_RUNNABLES = [
  'runtime_health',
  'intake_validate',
] as const;

export const REQUIRED_WINDMILL_ASYNC_RUNNABLES = [
  'local_ai_advisory',
  'workflow_dispatch',
  'prism_stage_dispatch',
  'job_status',
] as const;

export const REQUIRED_WINDMILL_JOB_HELPERS = [
  'getJob',
  'waitJob',
  'streamJob',
] as const;

export interface WmillContractVerificationReport {
  valid: boolean;
  status: 'WMILL_CONTRACT_VALIDATED' | 'WMILL_TS_NOT_GENERATED' | 'WMILL_CONTRACT_INCOMPLETE';
  registeredSyncRunnables: string[];
  registeredAsyncRunnables: string[];
  missingBindings: string[];
}

/**
 * Verifies an actual `wmill.ts` module object without fabricating registrations.
 */
export function verifyGeneratedWmillContract(
  candidate: unknown
): WmillContractVerificationReport {
  if (!candidate || typeof candidate !== 'object') {
    return {
      valid: false,
      status: 'WMILL_TS_NOT_GENERATED',
      registeredSyncRunnables: [],
      registeredAsyncRunnables: [],
      missingBindings: [
        ...REQUIRED_WINDMILL_SYNC_RUNNABLES.map((r) => `backend.${r}`),
        ...REQUIRED_WINDMILL_ASYNC_RUNNABLES.map((r) => `backendAsync.${r}`),
        ...REQUIRED_WINDMILL_JOB_HELPERS,
      ],
    };
  }

  const obj = candidate as Record<string, unknown>;
  const backend = (obj.backend && typeof obj.backend === 'object'
    ? obj.backend
    : {}) as Record<string, unknown>;
  const backendAsync = (obj.backendAsync && typeof obj.backendAsync === 'object'
    ? obj.backendAsync
    : {}) as Record<string, unknown>;

  const registeredSyncRunnables: string[] = [];
  const registeredAsyncRunnables: string[] = [];
  const missingBindings: string[] = [];

  for (const name of REQUIRED_WINDMILL_SYNC_RUNNABLES) {
    if (typeof backend[name] === 'function') {
      registeredSyncRunnables.push(name);
    } else {
      missingBindings.push(`backend.${name}`);
    }
  }

  for (const name of REQUIRED_WINDMILL_ASYNC_RUNNABLES) {
    if (typeof backendAsync[name] === 'function') {
      registeredAsyncRunnables.push(name);
    } else {
      missingBindings.push(`backendAsync.${name}`);
    }
  }

  for (const helper of REQUIRED_WINDMILL_JOB_HELPERS) {
    if (typeof obj[helper] !== 'function') {
      missingBindings.push(helper);
    }
  }

  const valid = missingBindings.length === 0;
  return {
    valid,
    status: valid ? 'WMILL_CONTRACT_VALIDATED' : 'WMILL_CONTRACT_INCOMPLETE',
    registeredSyncRunnables,
    registeredAsyncRunnables,
    missingBindings,
  };
}

/**
 * Fail-closed guard used when `./wmill.ts` has not yet been generated by `wmill app dev`.
 */
export function requireGeneratedWmillModule(): never {
  throw new Error(
    'Windmill native runtime unavailable: run `wmill app dev` against workspace `uor-offline-foundry` to generate `./wmill.ts`.'
  );
}
